"""Apply a Veyloria Studio pack (exported from the Studio's pack tab) to the repository.

Usage: python3 tools/studio/apply_pack.py <pack.json>

- Images      -> public/art/<path>.webp (replacing the shipped file; custom/ images are added)
- Maps        -> src/data/studio/maps/<id>.json
- Object kinds -> src/data/studio/objects.json (the full list)
- Tilesets    -> src/data/studio/tilesets.json (merged by id)
then src/data/studio/index.ts is regenerated. The game lays src/data/studio over the generated
data when it loads, so `npm run world:build` never overwrites these edits.
"""
import base64
import io
import json
import os
import re
import sys
from PIL import Image

ROOT = os.path.normpath(os.path.join(os.path.dirname(__file__), '..', '..'))
STUDIO = os.path.join(ROOT, 'src', 'data', 'studio')
SAFE = re.compile(r'^[a-z0-9_\-]+(/[a-z0-9_\-]+)*$')


def main(path):
    with open(path, encoding='utf-8') as f:
        pack = json.load(f)
    if pack.get('format') != 'veyloria-studio-pack' or pack.get('version') != 1:
        sys.exit('not a Veyloria Studio pack')
    os.makedirs(os.path.join(STUDIO, 'maps'), exist_ok=True)

    for name, url in pack.get('images', {}).items():
        if not SAFE.match(name):
            sys.exit(f'bad image path: {name}')
        raw = base64.b64decode(url.split(',', 1)[1])
        out = os.path.join(ROOT, 'public', 'art', name + '.webp')
        os.makedirs(os.path.dirname(out), exist_ok=True)
        Image.open(io.BytesIO(raw)).convert('RGBA').save(out, 'WEBP', quality=92, method=6)
        print('image ', name)

    for mid, m in pack.get('maps', {}).items():
        if not SAFE.match(mid) or '/' in mid or m.get('id') != mid:
            sys.exit(f'bad map id: {mid}')
        with open(os.path.join(STUDIO, 'maps', mid + '.json'), 'w', encoding='utf-8') as f:
            json.dump(m, f, ensure_ascii=False, indent=1)
            f.write('\n')
        print('map   ', mid)

    if pack.get('objects'):
        with open(os.path.join(STUDIO, 'objects.json'), 'w', encoding='utf-8') as f:
            f.write('[\n' + ',\n'.join('  ' + json.dumps(o, ensure_ascii=False) for o in pack['objects']) + '\n]\n')
        print('objects', len(pack['objects']))

    if pack.get('tilesets'):
        tpath = os.path.join(STUDIO, 'tilesets.json')
        current = {t['id']: t for t in json.load(open(tpath, encoding='utf-8'))} if os.path.exists(tpath) else {}
        current.update(pack['tilesets'])
        with open(tpath, 'w', encoding='utf-8') as f:
            json.dump(list(current.values()), f, ensure_ascii=False, indent=1)
            f.write('\n')
        print('tilesets', ', '.join(pack['tilesets']))

    write_index()


def write_index():
    maps = sorted(f[:-5] for f in os.listdir(os.path.join(STUDIO, 'maps')) if f.endswith('.json'))
    has_obj = os.path.exists(os.path.join(STUDIO, 'objects.json'))
    has_ts = os.path.exists(os.path.join(STUDIO, 'tilesets.json'))
    lines = [
        '// Studio layer: edits made in the Veyloria Studio and applied to the repository with',
        '// tools/studio/apply_pack.py. They are laid over the generated data when it loads, so',
        '// `npm run world:build` never overwrites them. Regenerated by apply_pack.py.',
        "import type { MapDef, ObjectKindDef, TilesetDef } from '../../core/types';",
    ]
    lines += [f"import m{i} from './maps/{m}.json';" for i, m in enumerate(maps)]
    if has_obj:
        lines.append("import objects from './objects.json';")
    if has_ts:
        lines.append("import tilesets from './tilesets.json';")
    lines += [
        '',
        f"export const STUDIO_MAPS: MapDef[] = [{', '.join(f'm{i}' for i in range(len(maps)))}] as unknown as MapDef[];",
        f"export const STUDIO_OBJECTS: ObjectKindDef[] | null = {'objects as unknown as ObjectKindDef[]' if has_obj else 'null'};",
        f"export const STUDIO_TILESETS: TilesetDef[] = {'tilesets as unknown as TilesetDef[]' if has_ts else '[]'};",
    ]
    with open(os.path.join(STUDIO, 'index.ts'), 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines) + '\n')


if __name__ == '__main__':
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
